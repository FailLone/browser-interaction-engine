import { it, expect } from 'vitest';
import { chromium } from 'playwright';
import { createServer as createViteServer } from 'vite';
import { resolve } from 'node:path';
import { BrowserEngine } from '@interaction/browser';
import { MemoryStore } from '@interaction/storage-memory';
import type { RuleAutomation, RulePluginRun } from '@interaction/rules';
import { createServer } from '../apps/server/src/server.js';
import { fixtureServer } from './helpers.js';

it('creates an automatically checked session from the UI and shows a historical modal defect after DFS closes it', async () => {
  const fixture = await fixtureServer(undefined, { ruleDefects: true });
  const engine = new BrowserEngine({ persistence: new MemoryStore() });
  const app = await createServer(engine); await app.listen({ host: '127.0.0.1', port: 0 });
  const ui = await createViteServer({ root: resolve('apps/ui'), logLevel: 'error', server: { port: 0, strictPort: false, proxy: { '/v1': `http://127.0.0.1:${(app.server.address() as any).port}` } } }); await ui.listen();
  const browser = await chromium.launch({ headless: true }); const page = await browser.newPage({ viewport: { width: 1600, height: 1200 } });
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  const posts: string[] = []; page.on('request', r => { if (r.method() === 'POST') posts.push(r.url()); });
  try {
    await page.goto(`http://127.0.0.1:${(ui.httpServer!.address() as any).port}`);
    await page.getByLabel('起始网址', { exact: true }).fill(fixture.url);
    expect(await page.getByLabel('遍历时自动检查规则', { exact: true }).isChecked()).toBe(true);
    await page.getByRole('button', { name: '＋ 创建探索会话', exact: true }).click();
    await page.getByRole('button', { name: '▶ DFS 探索', exact: true }).waitFor();
    const sid = engine.sessions()[0].id;
    await expect.poll(() => engine.list<RuleAutomation>(sid, 'rule-automation')[0]?.enabled).toBe(true);
    await page.getByRole('button', { name: '▶ DFS 探索', exact: true }).click();
    await expect.poll(() => engine.session(sid).status, { timeout: 90000 }).toBe('finished');
    await expect.poll(() => engine.list<RuleAutomation>(sid, 'rule-automation')[0]?.completedCount).toBe(engine.listInspections(sid, { limit: 500 }).items.length);
    const run = engine.list<RulePluginRun>(sid, 'rule-plugin-run').find(r => r.results.some(p => p.status === 'completed' && p.report.checks.some(c => c.code === 'CONTROL_CLIPPING_SUSPECTED' && c.target && p.targetLabels[c.target.nodeId] === 'Done')))!;
    expect(run).toBeDefined();
    await page.getByRole('button', { name: 'UI 检查', exact: true }).click();
    await page.getByRole('button', { name: `查看 #${run.history.lastSequence}`, exact: true }).click();
    const panel = page.getByRole('region', { name: '规则插件', exact: true });
    await panel.getByText('控件边界可能被容器裁切', { exact: true }).waitFor();
    expect(await panel.getByRole('region', { name: '控件裁切结果' }).innerText()).toContain('Done');
    expect(await panel.innerText()).toContain('遍历自动检测已保存');
    const last = engine.listInspections(sid, { limit: 500 }).items.at(-1)!;
    await page.getByRole('button', { name: `查看 #${last.sequence}`, exact: true }).click();
    const historical = panel.getByRole('region', { name: '控件裁切结果' }).locator('.rule-check').filter({ has: page.locator('b').filter({ hasText: /^Done$/ }) });
    await historical.getByText('历史记录 · 当前未复查 · 警告', { exact: true }).waitFor();
    expect(await historical.innerText()).toContain('保留此前的裁切记录');
    expect(posts.some(p => p.endsWith('/rule-runs'))).toBe(false);
    await page.reload(); await page.locator('.session-item').first().click();
    await page.getByRole('button', { name: 'UI 检查', exact: true }).click();
    await page.getByRole('button', { name: `查看 #${run.history.lastSequence}`, exact: true }).click();
    await panel.getByText('控件边界可能被容器裁切', { exact: true }).waitFor();
    expect(errors).toEqual([]);
  } finally { await browser.close(); await ui.close(); await app.close(); await engine.close(); await fixture.server.close(); }
}, 120000);
