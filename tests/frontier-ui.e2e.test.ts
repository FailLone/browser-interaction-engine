import { expect, it } from 'vitest';
import { chromium } from 'playwright';
import { createServer as createViteServer } from 'vite';
import { resolve } from 'node:path';
import type { FrontierItem } from '@interaction/browser';
import { createServer } from '../apps/server/src/server.js';
import { act, fixtureServer, testEngine } from './helpers.js';

it('shows completed parent work without legacy overlay duplicates and explains branch recovery failures', async () => {
  const fixture = await fixtureServer(); const t = await testEngine(fixture.url, { contextRules: [] });
  const app = await createServer(t.engine); await app.listen({ host: '127.0.0.1', port: 0 });
  const ui = await createViteServer({ root: resolve('apps/ui'), logLevel: 'error', server: { port: 0, strictPort: false, proxy: { '/v1': `http://127.0.0.1:${(app.server.address() as any).port}` } } }); await ui.listen();
  const browser = await chromium.launch({ headless: true }); const page = await browser.newPage();
  try {
    const parentState = t.engine.observation(t.sessionId).stateId;
    const entry = await t.engine.createCheckpoint(t.sessionId, 'entry');
    await act(t.engine, t.sessionId, 'Other settings');
    const action = t.engine.actions(t.sessionId).find(a => a.label === 'Amount')!;
    t.engine.store.put('frontier', { id: 'legacy-overlay-amount', sessionId: t.sessionId, key: 'legacy-overlay-amount', stateId: action.stateId, contextKey: '{}', action, status: 'blocked', reason: 'outside_active_boundary', unblock: action.preconditions.blockers![0].unblock, attempts: [], depth: 1 } satisfies FrontierItem);
    await act(t.engine, t.sessionId, 'Done'); await act(t.engine, t.sessionId, 'Amount', 'fill', '2');
    await t.engine.reachCheckpoint(t.sessionId, entry.id);
    await act(t.engine, t.sessionId, 'Price', 'fill', '0.01');
    const priceState = t.engine.observation(t.sessionId).stateId;
    await act(t.engine, t.sessionId, 'Amount', 'fill', '0.001');
    const sample = t.engine.store.list<FrontierItem>('frontier', t.sessionId).find(f => f.stateId === parentState && f.action.label === 'Amount' && f.action.value === '0.001')!;
    sample.status = 'blocked'; sample.reason = 'Cannot restore checkpoint: no verified return path and business state requires an environment reset'; t.engine.store.put('frontier', sample);
    const unreachable = t.engine.list<FrontierItem>(t.sessionId, 'frontier').find(f => f.stateId === parentState && f.action.label === 'Post only')!;
    unreachable.status = 'blocked'; unreachable.reason = 'Business state may have changed; environment reset required'; unreachable.unblock = 'Reach the branch checkpoint or repair its preconditions'; t.engine.store.put('frontier', unreachable);
    await page.goto(`http://127.0.0.1:${(ui.httpServer!.address() as any).port}`);
    await page.locator('.session-item').first().click();
    await page.getByRole('button', { name: '探索待办', exact: true }).click();
    const rows = page.locator('.tab-content tbody tr');
    await rows.first().waitFor();
    expect(await rows.count()).toBe(t.engine.list<FrontierItem>(t.sessionId, 'frontier').length);
    const amount = page.locator(`.frontier-group[data-control-id="${action.controlId}"][data-kind="fill"]`);
    expect(await amount.count()).toBe(1);
    expect(await amount.locator(':scope > summary').innerText()).toContain('已探索，仍有样本受阻');
    const blockedSample = amount.locator(`tr[data-frontier-id="${sample.id}"]`);
    expect(await blockedSample.innerText()).toContain('"0.001"');
    expect(await blockedSample.innerText()).toContain('样本受阻');
    expect(await blockedSample.innerText()).toContain('尚未执行');
    expect(await blockedSample.innerText()).toContain('无法返回所属界面');
    expect(await blockedSample.locator('.state-facts').innerText()).toContain('BTC/USDT');
    expect(await blockedSample.locator('.state-facts').innerText()).toContain('Limit');
    expect(await blockedSample.locator('.frontier-differences').innerText()).toContain(priceState.slice(0, 8));
    expect(await blockedSample.locator('.state-change').innerText()).toContain('Price');
    expect(await blockedSample.locator('.state-change').innerText()).toContain('0.01 → 空');
    const success = t.engine.getFrontier(t.sessionId).find(f => f.action.value === '2' && f.action.label === 'Amount')!;
    await amount.getByLabel('Amount 对照记录').selectOption(success.id);
    expect(await blockedSample.locator('.frontier-differences').innerText()).toContain('执行前界面相同，仅输入样本不同');
    expect(await blockedSample.locator('.state-change').innerText()).toContain('"2" → "0.001"');
    await blockedSample.getByText('完整界面摘要 / 业务上下文', { exact: true }).click();
    expect(await blockedSample.innerText()).toContain('未记录业务上下文；上方为实际记录的界面状态。');
    const actionCount = t.engine.session(t.sessionId).actionCount;
    await blockedSample.getByRole('button', { name: '查看历史界面' }).click();
    await page.getByRole('button', { name: '返回当前', exact: true }).waitFor();
    expect(t.engine.session(t.sessionId).actionCount).toBe(actionCount);
    expect(await amount.locator('tbody tr').filter({ has: page.getByRole('cell', { name: '"2"', exact: true }) }).innerText()).toContain('已执行成功');
    expect(await page.locator('.tab-content').innerText()).not.toContain('Close and verify exit');
    expect(await page.locator(`tr[data-frontier-id="${unreachable.id}"]`).innerText()).toContain('无法返回所属界面');
  } finally { await browser.close(); await ui.close(); await app.close(); await t.close(); await fixture.server.close(); }
});
